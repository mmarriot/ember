import { describe, expect, it } from "vitest";
import { devicePixels } from "./engine";

describe("devicePixels", () => {
  // Chromium's own answer (ResizeObserver devicePixelContentBoxSize, at a real device scale factor) for a canvas at
  // these places on the page: [dpr, left, top, right, bottom (the bounding box, CSS px), width, height (device px)].
  const measured: [number, number, number, number, number, number, number][] = [
    [1.25, 340, 56, 1440, 860, 1375, 1005],
    [1.25, 341, 56, 1440, 860, 1374, 1005], // floor(1099 * 1.25) = 1373
    [1.25, 341.3000183105469, 56.400001525878906, 1440.0000915527344, 860.0000381469727, 1373, 1004],
    [1.25, 337, 55, 1436.5, 856.25, 1375, 1001],
    [1.25, 0, 0, 510.01251220703125, 626.8250122070312, 638, 784],
    [1.5, 341, 56, 1440, 860, 1648, 1206],
    [1.5, 341.29168701171875, 56.395835876464844, 1439.9896850585938, 859.9895858764648, 1648, 1205],
    [1.5, 337, 55, 1436.5, 856.25, 1649, 1201],
    [1.5, 0, 0, 510.01043701171875, 626.8229370117188, 765, 940],
    [1.75, 340, 56.000003814697266, 1440, 860.0000648498535, 1925, 1407],
    [1.75, 341, 56.000003814697266, 1440, 860.0000648498535, 1923, 1407],
    [1.75, 341.2946472167969, 56.392860412597656, 1439.9911804199219, 859.9911270141602, 1923, 1406],
    [1.75, 337, 55.000003814697266, 1436.5, 856.2500648498535, 1924, 1402], // floor(1100 * 1.75) = 1925
    [1.75, 0, 0, 510.0089416503906, 626.8214721679688, 893, 1097],
    [2.5, 341, 56, 1440, 860, 2747, 2010],
    [2.5, 341.3000183105469, 56.400001525878906, 1440.0000915527344, 860.0000381469727, 2747, 2009],
    [2.5, 337, 55, 1436.5, 856.25, 2748, 2003],
    [2.5, 0, 0, 510.01251220703125, 626.8250122070312, 1275, 1567],
  ];
  it.each(measured)("at %f: the box from (%f, %f) to (%f, %f) covers %i x %i", (dpr, left, top, right, bottom, w, h) =>
    expect(devicePixels({ left, top, right, bottom }, dpr)).toEqual([w, h]),
  );
});
